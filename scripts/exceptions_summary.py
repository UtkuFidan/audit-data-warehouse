"""Write reports/exceptions_summary.md from the audit_exceptions mart (real counts)."""

import sys
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT / "audit_dw.duckdb"
OUT = ROOT / "reports" / "exceptions_summary.md"
MANUAL_JOURNALS = ("manual journals", "marts.fct_journal_entries where is_manual")


def main() -> None:
    con = duckdb.connect(str(DB), read_only=True)
    by_test = con.execute(
        """
        select test_id, risk, count(*) as exceptions
        from marts.audit_exceptions
        group by test_id, risk
        order by exceptions desc, test_id
        """
    ).fetchall()
    total = sum(r[2] for r in by_test)
    populations = {
        "dup_invoice_exact": ("invoices", "staging.stg_invoices"),
        "split_purchase": ("purchase orders", "staging.stg_purchase_orders"),
        "bank_change_payment": ("payments", "staging.stg_payments"),
        "sod_conflict": ("user accounts", "staging.stg_user_accounts"),
        "leaver_active_account": ("user accounts", "staging.stg_user_accounts"),
        "payment_before_vendor": ("payments", "staging.stg_payments"),
        "dup_invoice_fuzzy": ("invoices", "staging.stg_invoices"),
        "benford_vendor": ("vendors with invoices", "intermediate.int_vendor_benford"),
        "je_round_amount": MANUAL_JOURNALS,
        "je_weekend_holiday": MANUAL_JOURNALS,
        "je_unauthorized_poster": MANUAL_JOURNALS,
    }
    lines = [
        "# Exceptions summary",
        "",
        "Generated by `make report` from `marts.audit_exceptions` (synthetic FY2025 data).",
        "Each exception is an item to follow up, not a conclusion of error or fraud.",
        "",
        f"Total exceptions: {total} across {len(by_test)} tests.",
        "",
        "| test_id | risk | population | records tested | exceptions |",
        "|---|---|---|---:|---:|",
    ]
    for test_id, risk, n in by_test:
        label, table = populations[test_id]
        tested = con.execute(f"select count(*) from {table}").fetchone()[0]
        lines.append(f"| `{test_id}` | {risk} | {label} | {tested:,} | {n} |")
    lines += ["", "## Sample evidence", ""]
    for test_id, _, _ in by_test:
        row = con.execute(
            "select entity, evidence from marts.audit_exceptions where test_id = ? order by entity limit 1",
            [test_id],
        ).fetchone()
        lines.append(f"- `{test_id}` / `{row[0]}`: {row[1]}")
    lines.append("")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)} ({total} exceptions)", file=sys.stderr)


if __name__ == "__main__":
    main()
